/**
 * The agent's local loop for an app with data, without real resources or credentials.
 *
 * Usage (through `python -m sandbox_runtime.conformance app-dev`):
 *   app-dev.mjs [--dir <app dir>] [--entry <worker module>] [--assets <build dir>]
 *
 * Derives, from openinspect.app.json and never by hand, a Wrangler configuration with a local copy
 * of every declared binding, and a dev entry that does what the platform guard does in
 * production: drop identity headers a client could forge and set the signed-in user. Code that
 * works here reads identity the same way deployed. Everything lands in `.openinspect/dev/`, which
 * ignores itself in git; secrets get placeholder values in `.dev.vars` that a person may replace.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";

const CONTRACT = JSON.parse(
  readFileSync(new URL("./app_data_contract.json", import.meta.url), "utf8")
);
const OUTPUT_DIR = join(".openinspect", "dev");
const DEV_USER = { sub: "dev-user", email: "dev-user@example.invalid" };

function option(args, name) {
  const index = args.indexOf(name);
  return index === -1 ? null : (args[index + 1] ?? null);
}

/** A path relative to the generated config, which Wrangler resolves against its own directory. */
function fromOutput(appDir, path) {
  return relative(join(appDir, OUTPUT_DIR), resolve(appDir, path)).split("\\").join("/");
}

function wranglerConfig(appDir, manifest, assets) {
  const data = Object.entries(manifest.data ?? {}).sort(([a], [b]) => (a < b ? -1 : 1));
  const local = (binding) => `local-${binding.toLowerCase().replaceAll("_", "-")}`;
  return {
    name: `${manifest.name}-dev`,
    main: "dev-entry.mjs",
    ...(assets
      ? {
          assets: {
            directory: fromOutput(appDir, assets),
            binding: "ASSETS",
            run_worker_first: true,
          },
        }
      : {}),
    d1_databases: data
      .filter(([, declaration]) => declaration.kind === "d1")
      .map(([binding, declaration]) => ({
        binding,
        database_name: local(binding),
        database_id: local(binding),
        migrations_dir: fromOutput(appDir, declaration.migrations ?? "migrations"),
      })),
    kv_namespaces: data
      .filter(([, declaration]) => declaration.kind === "kv")
      .map(([binding]) => ({ binding, id: local(binding) })),
    r2_buckets: data
      .filter(([, declaration]) => declaration.kind === "r2")
      .map(([binding]) => ({ binding, bucket_name: local(binding) })),
    vars: {
      APP_HOSTNAME: "localhost",
      OI_APP_NAME: manifest.name,
      CF_ACCESS_AUD: "dev",
      CF_ACCESS_TEAM_DOMAIN: "https://dev.invalid",
    },
  };
}

function devEntry(appDir, entry) {
  const strip = JSON.stringify([
    ...CONTRACT.forbiddenIdentityHeaders,
    CONTRACT.identityHeaders.sub,
    CONTRACT.identityHeaders.email,
  ]);
  const app = entry
    ? `import app from ${JSON.stringify(fromOutput(appDir, entry))};`
    : "const app = { fetch: (request, env) => env.ASSETS.fetch(request) };";
  return `// Generated by app-dev from ${CONTRACT.manifestFile}. Do not edit or commit.
${app}

export default {
  ...app,
  fetch(request, env, ctx) {
    const headers = new Headers(request.headers);
    for (const name of ${strip}) headers.delete(name);
    headers.set(${JSON.stringify(CONTRACT.identityHeaders.sub)}, ${JSON.stringify(DEV_USER.sub)});
    headers.set(${JSON.stringify(CONTRACT.identityHeaders.email)}, ${JSON.stringify(DEV_USER.email)});
    return app.fetch(new Request(request, { headers }), env, ctx);
  },
};
`;
}

/** Keeps every value already present; adds a placeholder for each declared secret. */
function devVars(existing, secrets) {
  const present = new Set(
    existing
      .split("\n")
      .map((line) => line.split("=")[0].trim())
      .filter(Boolean)
  );
  const added = secrets
    .filter((name) => !present.has(name))
    .map((name) => `${name}=dev-placeholder`);
  return [existing.trimEnd(), ...added].filter(Boolean).join("\n") + "\n";
}

function main(args) {
  const appDir = resolve(option(args, "--dir") ?? ".");
  const manifestPath = join(appDir, CONTRACT.manifestFile);
  if (!existsSync(manifestPath)) {
    console.error(
      `No ${CONTRACT.manifestFile} in ${appDir}. Create it first, then run app-dev again.`
    );
    return 1;
  }
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  const output = join(appDir, OUTPUT_DIR);
  mkdirSync(output, { recursive: true });
  writeFileSync(join(output, ".gitignore"), "*\n");
  const config = join(output, "wrangler.jsonc");
  writeFileSync(
    config,
    `// Generated by app-dev from ${CONTRACT.manifestFile}. Do not edit; deploy-app never reads it.\n${JSON.stringify(wranglerConfig(appDir, manifest, option(args, "--assets")), null, 2)}\n`
  );
  writeFileSync(join(output, "dev-entry.mjs"), devEntry(appDir, option(args, "--entry")));
  const varsPath = join(output, ".dev.vars");
  const existing = existsSync(varsPath) ? readFileSync(varsPath, "utf8") : "";
  writeFileSync(varsPath, devVars(existing, manifest.secrets ?? []));
  const configArg = relative(process.cwd(), config);
  const databases = Object.entries(manifest.data ?? {}).filter(([, d]) => d.kind === "d1");
  console.log(`Wrote ${relative(process.cwd(), output)}/ (git ignores it).`);
  console.log("Next:");
  for (const [binding] of databases) {
    console.log(`  npx wrangler d1 migrations apply ${binding} --local --config ${configArg}`);
  }
  console.log(`  npx wrangler dev --config ${configArg}`);
  console.log(
    `Requests arrive as ${DEV_USER.email} (${CONTRACT.identityHeaders.sub}: ${DEV_USER.sub}).`
  );
  return 0;
}

process.exitCode = main(process.argv.slice(2));
